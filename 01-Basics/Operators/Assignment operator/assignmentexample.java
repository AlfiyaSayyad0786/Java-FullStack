package Assignment;

public class AssignmentExample {
    public static void main(String[] args) {

        int a = 10;

        System.out.println("Initial value = " + a);

        a += 5;
        System.out.println("After += " + a);

        a -= 3;
        System.out.println("After -= " + a);

        a *= 2;
        System.out.println("After *= " + a);

        a /= 4;
        System.out.println("After /= " + a);

        a %= 3;
        System.out.println("After %= " + a);
    }
}